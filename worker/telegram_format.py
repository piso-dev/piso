"""Safe, stdlib-only Telegram HTML for the supervisor's active chat path."""
import html
import re
from urllib.parse import urlsplit


def redact(text):
    text = str(text or "")
    # Known credential shapes, including gateway placeholders.
    text = re.sub(r"\b(?:piso_[A-Za-z0-9_-]+|sk-[A-Za-z0-9_-]{12,}|gh[pousr]_[A-Za-z0-9_]+|\d{5,}:[A-Za-z0-9_-]{30,})\b", "[redacted]", text)
    text = re.sub(r"(?i)(bearer\s+)[^\s\"']+", r"\1[redacted]", text)
    text = re.sub(r"(?i)((?:[\w-]*(?:token|secret|password|api[_-]?key)[\w-]*)[\"']?\s*(?:=|:|\s)\s*)(?:\"[^\"]*\"|'[^']*'|[^\s&,;]+)", r"\1[redacted]", text)
    text = re.sub(r"(https?://)[^/\s:@]+:[^/\s@]+@", r"\1[redacted]@", text)
    return text


def escape(text):
    return html.escape(str(text), quote=False)


def preview(text, limit=100):
    text = " ".join(redact(text).split())
    return text if len(text) <= limit else text[:limit - 1] + "…"


_INLINE = re.compile(r"`[^`\n]+`|\*\*[^*\n]+\*\*|__[^_\n]+__|~~[^~\n]+~~|\[[^\]\n]+\]\([^)\s]+\)|\*[^*\n]+\*|_[^_\n]+_")


def inline(text):
    out, pos = [], 0
    for match in _INLINE.finditer(text):
        out.append(escape(text[pos:match.start()]))
        value = match.group()
        if value.startswith('`'):
            out.append('<code>' + escape(value[1:-1]) + '</code>')
        elif value.startswith('['):
            label, url = value[1:-1].split('](', 1)
            try:
                safe = len(url) <= 512 and urlsplit(url).scheme in ('http', 'https', 'tg')
            except ValueError:
                safe = False
            out.append('<a href="' + html.escape(url, quote=True) + '">' + escape(label) + '</a>' if safe else escape(value))
        else:
            width = 2 if value[:2] in ('**', '__', '~~') else 1
            tag = 's' if value.startswith('~~') else 'b' if width == 2 else 'i'
            out.append('<' + tag + '>' + escape(value[width:-width]) + '</' + tag + '>')
        pos = match.end()
    out.append(escape(text[pos:]))
    return ''.join(out)


def markdown(text):
    """Answers: escaped prose, emphasis, safe links, headings and code fences.

    Incomplete fences are valid code until the end, useful for interrupted turns.
    Arbitrary model-supplied HTML is never trusted.
    """
    out, code = [], None
    for line in text.splitlines(keepends=True):
        if line.startswith('```'):
            if code is not None:
                out.append('<pre>' + escape(''.join(code)) + '</pre>\n')
                code = None
            else:
                code = []
        elif code is not None:
            code.append(line)
        else:
            heading = re.match(r'^#{1,6}\s+(.+)', line)
            out.append('<b>' + escape(heading[1]) + '</b>\n' if heading else inline(line))
    if code is not None:
        out.append('<pre>' + escape(''.join(code)) + '</pre>')
    return ''.join(out).strip()


def chunks(rendered, limit=3800):
    """Split on complete entities/Unicode characters, close and reopen all tags.

    Budget UTF-8 bytes (conservative vs Telegram's character limit and the
    gateway's byte cap). Every piece is independently valid Telegram HTML.
    Only accepts HTML generated by this module/the supervisor.
    """
    tokens = re.findall(r'<[^>]+>|&(?:[A-Za-z]+|#\d+|#x[0-9a-fA-F]+);|[^<&]|[<&]', rendered)
    stack, out, current = [], [], ''
    def closers():
        return ''.join('</' + name + '>' for name, _ in reversed(stack))
    for token in tokens:
        closing = re.fullmatch(r'</(\w+)>', token)
        opening = re.match(r'<(\w+)(?:\s[^>]*)?>$', token)
        next_stack = list(stack)
        if closing:
            if next_stack:
                next_stack.pop()
        elif opening:
            next_stack.append((opening[1], token))
        suffix = ''.join('</' + name + '>' for name, _ in reversed(next_stack))
        if len((current + token + suffix).encode()) > limit:
            if not current or len((''.join(tag for _, tag in stack) + token + suffix).encode()) > limit:
                raise ValueError('HTML token exceeds message budget')
            out.append(current + closers())
            current = ''.join(tag for _, tag in stack)
        current += token
        stack = next_stack
    if current:
        out.append(current + closers())
    return out
